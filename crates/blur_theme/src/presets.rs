//! Built-in Blur themes matching the exact Stitch Material-3 tonal palettes
//! (`Furusato Slate` / Quiet Precision, `Obsidian Precision`, `Warm Amber Soft`,
//! `Tokyo Dusk`, `Rose Pine Moon`, `E-Ink Paper Light`).

use crate::{ColorPalette, SyntaxPalette, TerminalPalette, ThemeDef};

/// Returns the 6 built-in Blur themes matching the Stitch Theme Switcher.
pub fn builtin_themes() -> Vec<ThemeDef> {
    vec![
        furusato_slate(),
        obsidian_precision(),
        warm_amber_soft(),
        tokyo_dusk(),
        rose_pine_moon(),
        e_ink_paper_light(),
    ]
}

fn s(v: &str) -> String {
    v.to_string()
}

